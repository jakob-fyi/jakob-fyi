/**
 * Turns the content data (content/*.json) into the `fyi-jakob-*` markup that
 * src/index.html contains. Pure functions only - file access lives in
 * scripts/build-html.mjs.
 */

const INDENT = "    ";
const MAX_LINE = 140;

/** Data field -> HTML attribute, in the order the attributes are written. */
const ATTRIBUTES = [
    ["id", "id"],
    ["title", "maintitle"],
    ["subtitle", "subtitle"],
    ["tags", "tags"],
    ["place", "place"],
    ["date", "date"],
    ["time", "time"],
    ["tagline", "tagline"],
    ["link", "link"],
    ["target", "target"],
    ["added", "added"]
];

export const escapeAttribute = (value) =>
    String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

/** Tags keep the familiar `tags='["A", "B"]'` form. */
const tagsAttribute = (tags) => {
    const json = `[${tags.map((tag) => JSON.stringify(tag)).join(", ")}]`;
    return `tags='${json.replaceAll("&", "&amp;").replaceAll("'", "&#39;")}'`;
};

const attribute = (name, value) => (name === "tags" ? tagsAttribute(value) : `${name}="${escapeAttribute(value)}"`);

const indent = (text, depth) =>
    text
        .split("\n")
        .map((line) => (line ? INDENT.repeat(depth) + line : line))
        .join("\n");

/**
 * Renders `<tag attrs>children</tag>`; attributes go on one line when that
 * stays short, otherwise one per line.
 */
export const element = (tag, attributes, children = []) => {
    const singleLine = `<${tag}${attributes.map((a) => ` ${a}`).join("")}>`;
    const open =
        singleLine.length <= MAX_LINE || attributes.length === 0 ? singleLine : `<${tag}\n${attributes.map((a) => INDENT + a).join("\n")}\n>`;
    if (children.length === 0) return `${open}</${tag}>`;
    return `${open}\n${indent(children.join("\n"), 1)}\n</${tag}>`;
};

const entryAttributes = (entry) => ATTRIBUTES.filter(([field]) => entry[field] !== undefined).map(([field, name]) => attribute(name, entry[field]));

const image = ({ src, alt, width, height }) =>
    [
        "<img",
        'loading="lazy"',
        'decoding="async"',
        ...(width !== undefined ? [`width="${width}"`] : []),
        ...(height !== undefined ? [`height="${height}"`] : []),
        `src="${escapeAttribute(src)}"`,
        `alt="${escapeAttribute(alt)}"`,
        "/>"
    ].join(" ");

const body = (value) => (Array.isArray(value) ? value : [value]);

export const renderEntry = (entry) => {
    const children = [...(entry.images ?? []).map(image), ...(entry.body !== undefined ? body(entry.body) : [])];
    return element(`fyi-jakob-${entry.type}`, entryAttributes(entry), children);
};

const visible = (entries) => entries.filter((entry) => !entry.hidden);

export const renderSection = (section) =>
    element(
        "fyi-jakob-section",
        [...(section.id ? [attribute("id", section.id)] : []), ...(section.title ? [attribute("maintitle", section.title)] : [])],
        visible(section.entries).map(renderEntry)
    );

export const renderCollapsible = (collapsible) =>
    element(
        "fyi-jakob-collapsible",
        [
            attribute("id", collapsible.id),
            attribute("heading", collapsible.heading),
            ...(collapsible.summary ? [attribute("summary", collapsible.summary)] : []),
            ...(collapsible.summaryLabel ? [attribute("summary-label", collapsible.summaryLabel)] : [])
        ],
        collapsible.sections.map(renderSection)
    );

/** Renders one content file (a section or a collapsible); a hidden block renders nothing. */
export const renderBlock = (block) => {
    if (block.hidden) return "";
    return block.type === "collapsible" ? renderCollapsible(block) : renderSection(block);
};

export const PLACEHOLDER = /^([ \t]*)<!--\s*@content\s+([\w-]+)\s*-->[ \t]*(?:\n|$)/gm;

export const GENERATED_NOTICE = "<!-- Generated by scripts/build-html.mjs - edit content/*.json and src/index.template.html instead. -->";

/**
 * Replaces every `<!-- @content name -->` line in the template with the
 * rendered block of the same name, indented like the placeholder.
 */
export const renderPage = (template, blocks) => {
    const page = template.replace(PLACEHOLDER, (_, space, name) => {
        if (!(name in blocks)) throw new Error(`No content for placeholder "${name}"`);
        const markup = renderBlock(blocks[name]);
        if (!markup) return "";
        return `${markup
            .split("\n")
            .map((line) => (line ? space + line : line))
            .join("\n")}\n`;
    });
    return page.replace(/^(<!doctype html>)/i, `$1\n${GENERATED_NOTICE}`);
};
